new = '''如果 $\\hat{\\beta}_t$ 存在时间序列自相关（这在实际中很常见），公式 (5.19) 的标准误仍然有偏。

> **什么叫"因子收益率的时间序列自相关"？** 这里说的不是"一只股票的EP值这月高、下月还高"（那是因子值本身的持续性），而是指"EP因子的**赚钱能力**有惯性"——如果这个月EP因子表现好（$\\hat{\\beta}_t$为正），下个月也倾向于表现好。
>
> 为什么会这样？因为市场风格有周期：2016-2017年连续二十多个月价值股跑赢（$\\hat{\\beta}_t$持续为正）；2020-2021年连续十几个月价值股跑输（$\\hat{\\beta}_t$持续为负）。因子收益率不是"这月赚了、下月归零"的随机过程，而是倾向于"连续赚几个月、然后连续亏几个月"。这种"连续性"就是时间序列自相关。
>
> 它的后果：如果你天真地假设120个月的$\\hat{\\beta}_t$是独立的（互不相关），你会**低估**均值估计的不确定性——因为20个"连续为正"的月份提供的独立信息量远没有20个独立样本那么多。'''

