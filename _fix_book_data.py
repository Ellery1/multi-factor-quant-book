"""根据核实结果修正书中的数据"""

def patch(filepath, old, new, name):
    with open(filepath, 'r', encoding='utf-8') as f:
        c = f.read()
    if old in c:
        c = c.replace(old, new, 1)
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(c)
        print(f"  OK: {name}")
        return True
    else:
        print(f"  MISS: {name} -- {old[:60]}...")
        return False

