new = '''**FDR 控制（Benjamini-Hochberg, 1995）**[5]：

Bonferroni的问题在于"宁可错杀一千不可放过一个"——它控制的是"犯任何一个错误的概率"，所以门槛极高。BH方法换了一个更务实的目标：**我允许自己犯少量错误（比如在宣布有效的因子中，约5%其实是假的），但代价是我能发现更多真正有效的因子**。

> **核心思路**：想象你把10个因子按p值从小到大排成一队。排在最前面的（p最小的）最可能是"真的有效"。问题是：这个队伍从哪里开始"不可信"了？BH方法的直觉是——如果某个位置的p值"大到与随机噪声无法区分"，那从这个位置往后的所有因子都不可信。
>
> 具体来说：如果有10个因子，你期望其中约5%×10=0.5个是"碰巧显著的假阳性"。那排第$k$位的因子，它的"合理假阳性率"应该是$k/M \\times \\alpha$——位置越靠后（p越大），你对它的容忍度越高，因为它"踩雷"的概率也更大。如果某个因子的p值连这个"逐渐放宽的门槛"都超过了，说明它大概率不是真的。
>
> **类比**：就像面试筛选。前几名候选人你用严格标准（p值要很小才通过），后面的候选人你标准逐渐放宽（位置越靠后允许p越大）。但如果某个候选人连放宽后的标准都达不到——从他开始往后全部淘汰。

**步骤**：
1. 将 $M$ 个因子的p值排序：$p_{(1)} \\leq p_{(2)} \\leq ... \\leq p_{(M)}$（从"最可能有效"排到"最可能无效"）
2. 找到最大的 $k$ 使得 $p_{(k)} \\leq \\frac{k}{M} \\cdot \\alpha$（找到"最后一个还能通过逐渐放宽标准的位置"）
3. 拒绝前 $k$ 个零假设（即判定前 $k$ 个因子为"有效"，从第$k+1$个开始全部判为"不可信"）'''

